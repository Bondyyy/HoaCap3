function build(rows: Row[], chapter: Chapter): Question[] {
  return rows.map(
    (
      [
        lessonId,
        question,
        options,
        correctAnswer,
        explanation,
        difficulty = "easy",
        type = "choice",
      ],
      i,
    ) => ({
      id: `${chapter}-${i + 1}`,
      chapter,
      lessonId,
      type,
      difficulty,
      question,
      options: options.length ? options : undefined,
      correctAnswer,
      explanation,
      points: 1,
      sourceReference:
        chapter === "amino"
          ? "PDF trang 1–4; câu tự biên soạn"
          : "PDF trang 4–6; câu tự biên soạn",
    }),
  );
}
